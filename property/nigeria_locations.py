def seed_nigeria_locations():
    """
    Ensure all Nigerian states and their major cities exist in the database.
    Returns (created_states_count, created_cities_count).
    """
    from property.models import State, City
    
    states_created = 0
    cities_created = 0

    for state_name, state_data in NIGERIA_LOCATIONS.items():
        state_obj, s_created = State.objects.get_or_create(
            name=state_name,
            defaults={
                "code": state_data["code"],
                "is_active": True
            }
        )
        if s_created:
            states_created += 1

        for city_name in state_data["cities"]:
            _, c_created = City.objects.get_or_create(
                name=city_name,
                state=state_obj,
                defaults={"is_active": True}
            )
            if c_created:
                cities_created += 1

    return states_created, cities_created
